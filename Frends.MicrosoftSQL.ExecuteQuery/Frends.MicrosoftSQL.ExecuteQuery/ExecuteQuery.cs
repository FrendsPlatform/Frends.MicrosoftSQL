using System;
using System.ComponentModel;
using System.Data;
using System.Runtime.InteropServices;
using System.Security.Principal;
using System.Threading;
using System.Threading.Tasks;
using Frends.MicrosoftSQL.ExecuteQuery.Definitions;
using Frends.MicrosoftSQL.ExecuteQuery.Helpers;
using Microsoft.Data.SqlClient;
using Microsoft.SqlServer.Types;
using Newtonsoft.Json.Linq;
using SimpleImpersonation;
using IsolationLevel = System.Data.IsolationLevel;

namespace Frends.MicrosoftSQL.ExecuteQuery;

/// <summary>
/// MicrosoftSQL Task.
/// </summary>
public static class MicrosoftSQL
{
    /// <summary>
    /// Execute MSSQL query.
    /// [Documentation](https://tasks.frends.com/tasks/frends-tasks/Frends.MicrosoftSQL.ExecuteQuery)
    /// </summary>
    /// <param name="input">Input parameters</param>
    /// <param name="connection">Properties to set up connection</param>
    /// <param name="options">Optional parameters</param>
    /// <param name="cancellationToken">Token generated by Frends to stop this Task.</param>
    /// <returns>object { bool Success, int RecordsAffected, JToken Data, object Error { string Message, Exception AdditionalInfo } }</returns>
    public static async Task<Result> ExecuteQuery(
        [PropertyTab] Input input,
        [PropertyTab] Connection connection,
        [PropertyTab] Options options,
        CancellationToken cancellationToken)
    {
        try
        {
            ValidationHandler.Run(connection);
            if (connection.UseGivenUserCredentialsForRemoteConnections && !RuntimeInformation.IsOSPlatform(OSPlatform.Windows))
                throw new PlatformNotSupportedException("Simple impersonation feature is only supported on Windows machines.");
            var connectionString = GetConnectionString(connection);
            if (!connection.UseGivenUserCredentialsForRemoteConnections)
                return await ExecuteQueryInternal(input, connectionString, options, cancellationToken).ConfigureAwait(false);

            var domainAndUsername = (connection.Username ?? string.Empty).Split('\\');
            if (domainAndUsername.Length != 2)
            {
                throw new ArgumentException(
                    $@"Username field must be of format domain\username was: {connection.Username}");
            }

            var credentials = new UserCredentials(domainAndUsername[0], domainAndUsername[1], connection.Password);
            using var handle = credentials.LogonUser(LogonType.NewCredentials);
            return await WindowsIdentity.RunImpersonatedAsync(
                    handle,
                    async () => await ExecuteQueryInternal(input, connectionString, options, cancellationToken)
                        .ConfigureAwait(false))
                .ConfigureAwait(false);
        }
        catch (Exception ex)
        {
            return ex.Handle(options);
        }
    }

    internal static string GetConnectionString(Connection connection)
    {
        if (!connection.UseGivenUserCredentialsForRemoteConnections)
            return connection.ConnectionString;

        var builder = new SqlConnectionStringBuilder(connection.ConnectionString);
        if (!builder.IntegratedSecurity)
        {
            throw new ArgumentException(
                "ConnectionString must use Integrated Security=true when UseGivenUserCredentialsForRemoteConnections is enabled.");
        }

        builder.Pooling = false;
        return builder.ConnectionString;
    }

    private static async Task<Result> ExecuteQueryInternal(
        Input input,
        string connectionString,
        Options options,
        CancellationToken cancellationToken)
    {
        SqlConnection sqlCon = null;
        SqlCommand command;
        try
        {
            sqlCon = new SqlConnection(connectionString);
            await sqlCon.OpenAsync(cancellationToken).ConfigureAwait(false);

            command = sqlCon.CreateCommand();
            command.CommandTimeout = options.CommandTimeoutSeconds;
            command.CommandText = input.Query;
            command.CommandType = CommandType.Text;

            if (input.Parameters != null)
            {
                foreach (var parameter in input.Parameters)
                {
                    if (parameter.Value == null)
                    {
                        command.Parameters.AddWithValue(parameterName: parameter.Name, value: DBNull.Value);
                    }
                    else if (parameter.Value.GetType() == typeof(JValue))
                    {
                        if (((JToken)parameter.Value).Type == JTokenType.Null)
                        {
                            command.Parameters.AddWithValue(parameterName: parameter.Name, value: DBNull.Value);
                        }
                        else
                        {
                            command.Parameters.AddWithValue(
                                parameterName: parameter.Name,
                                value: parameter.Value.ToString());
                        }
                    }
                    else if (parameter.SqlDataType is SqlDataTypes.Auto)
                    {
                        command.Parameters.AddWithValue(
                            parameterName: parameter.Name,
                            value: parameter.Value ?? DBNull.Value);
                    }
                    else
                    {
                        var sqlDbType = (SqlDbType)Enum.Parse(typeof(SqlDbType), parameter.SqlDataType.ToString());
                        var commandParameter = command.Parameters.Add(parameter.Name, sqlDbType);
                        commandParameter.Value = parameter.Value ?? DBNull.Value;
                    }
                }
            }
        }
        catch (Exception ex)
        {
            sqlCon?.Dispose();
            return new Exception($"ExecuteQuery exception: {ex}", ex).Handle(options);
        }

        await using (sqlCon)
        await using (command)
        {
            if (options.SqlTransactionIsolationLevel is SqlTransactionIsolationLevel.None)
                return await ExecuteHandler(input, options, command, cancellationToken).ConfigureAwait(false);

            SqlTransaction transaction;
            try
            {
                transaction = sqlCon.BeginTransaction(GetIsolationLevel(options));
            }
            catch (Exception ex)
            {
                return ex.Handle(options);
            }

            await using (transaction)
            {
                command.Transaction = transaction;
                return await ExecuteHandler(input, options, command, cancellationToken).ConfigureAwait(false);
            }
        }
    }

    private static async Task<Result> ExecuteHandler(
        Input input,
        Options options,
        SqlCommand command,
        CancellationToken cancellationToken)
    {
        SqlDataReader dataReader = null;

        try
        {
            object dataObject;
            Result result;
            switch (input.ExecuteType)
            {
                case ExecuteTypes.Auto:
                    if (input.Query.ToLower().StartsWith("select"))
                    {
                        dataReader = await command.ExecuteReaderAsync(cancellationToken).ConfigureAwait(false);
                        result = new Result(
                            true,
                            dataReader.RecordsAffected,
                            await LoadData(dataReader, cancellationToken).ConfigureAwait(false));
                        await dataReader.CloseAsync().ConfigureAwait(false);
                        break;
                    }

                    dataObject = await command.ExecuteNonQueryAsync(cancellationToken).ConfigureAwait(false);
                    result = new Result(true, (int)dataObject, JToken.FromObject(new { AffectedRows = dataObject }));
                    break;
                case ExecuteTypes.NonQuery:
                    dataObject = await command.ExecuteNonQueryAsync(cancellationToken).ConfigureAwait(false);
                    result = new Result(true, (int)dataObject, JToken.FromObject(new { AffectedRows = dataObject }));
                    break;
                case ExecuteTypes.Scalar:
                    dataObject = await command.ExecuteScalarAsync(cancellationToken).ConfigureAwait(false);

                    // JToken.FromObject() method can't handle SqlGeography typed objects so we convert it into string.
                    if (dataObject is SqlGeography or SqlGeometry)
                        dataObject = dataObject.ToString();

                    result = new Result(true, 1, JToken.FromObject(new { Value = dataObject }));
                    break;
                case ExecuteTypes.ExecuteReader:
                    dataReader = await command.ExecuteReaderAsync(cancellationToken).ConfigureAwait(false);
                    result = new Result(
                        true,
                        dataReader.RecordsAffected,
                        await LoadData(dataReader, cancellationToken).ConfigureAwait(false));
                    await dataReader.CloseAsync().ConfigureAwait(false);
                    break;
                default:
                    throw new NotSupportedException();
            }

            if (command.Transaction != null)
                await command.Transaction.CommitAsync(cancellationToken).ConfigureAwait(false);

            return result;
        }
        catch (Exception ex)
        {
            // An open reader blocks any further command on the connection, including the rollback.
            if (dataReader is { IsClosed: false })
                await dataReader.CloseAsync().ConfigureAwait(false);

            Exception executionException;
            if (command.Transaction is null)
            {
                executionException = new Exception(
                    $"ExecuteHandler exception: 'Options.SqlTransactionIsolationLevel = None', so there was no transaction rollback. {ex}",
                    ex);
            }
            else
            {
                try
                {
                    await command.Transaction.RollbackAsync(cancellationToken).ConfigureAwait(false);
                }
                catch (Exception rollbackEx)
                {
                    return new Exception(
                        $"ExecuteHandler exception: An exception occurred on transaction rollback. Rollback exception: {rollbackEx}. ||  Exception leading to rollback: {ex}",
                        rollbackEx).Handle(options);
                }

                executionException = new Exception(
                    $"ExecuteHandler exception: (If required) transaction rollback completed without exception. {ex}.",
                    ex);
            }

            return executionException.Handle(options);
        }
        finally
        {
            if (dataReader is { IsClosed: false })
                await dataReader.CloseAsync().ConfigureAwait(false);
        }
    }

    private static async Task<JToken> LoadData(SqlDataReader reader, CancellationToken cancellationToken)
    {
        var table = new JArray();
        while (reader.HasRows)
        {
            while (await reader.ReadAsync(cancellationToken).ConfigureAwait(false))
            {
                var row = new JObject();
                for (var i = 0; i < reader.FieldCount; i++)
                {
                    object fieldValue = reader.GetValue(i);
                    object value;
                    if (fieldValue == DBNull.Value)
                        value = null;
                    else if (fieldValue is SqlGeography geography)
                        value = geography.ToString();
                    else if (fieldValue is SqlGeometry geometry)
                        value = geometry.ToString();
                    else
                        value = fieldValue;

                    row.Add(new JProperty(reader.GetName(i), value));
                }

                table.Add(row);
            }

            await reader.NextResultAsync(cancellationToken).ConfigureAwait(false);
        }

        return table;
    }

    private static IsolationLevel GetIsolationLevel(Options options)
    {
        return options.SqlTransactionIsolationLevel switch
        {
            SqlTransactionIsolationLevel.Unspecified => IsolationLevel.Unspecified,
            SqlTransactionIsolationLevel.ReadUncommitted => IsolationLevel.ReadUncommitted,
            SqlTransactionIsolationLevel.ReadCommitted => IsolationLevel.ReadCommitted,
            SqlTransactionIsolationLevel.RepeatableRead => IsolationLevel.RepeatableRead,
            SqlTransactionIsolationLevel.Serializable => IsolationLevel.Serializable,
            SqlTransactionIsolationLevel.Snapshot => IsolationLevel.Snapshot,
            _ => IsolationLevel.ReadCommitted,
        };
    }
}
