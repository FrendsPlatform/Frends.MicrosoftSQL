using System;
using System.ComponentModel;
using System.Data;
using System.Dynamic;
using System.Reflection;
using System.Runtime.InteropServices;
using System.Runtime.Loader;
using System.Security.Principal;
using System.Threading;
using System.Threading.Tasks;
using Dapper;
using Frends.MicrosoftSQL.BatchOperation.Definitions;
using Frends.MicrosoftSQL.BatchOperation.Helpers;
using Microsoft.Data.SqlClient;
using Newtonsoft.Json;
using Newtonsoft.Json.Converters;
using SimpleImpersonation;
using IsolationLevel = System.Data.IsolationLevel;

namespace Frends.MicrosoftSQL.BatchOperation;

/// <summary>
/// MicrosoftSQL BatchOperation Task.
/// </summary>
public static class MicrosoftSQL
{
    // Mem cleanup.
    static MicrosoftSQL()
    {
        var currentAssembly = Assembly.GetExecutingAssembly();
        var currentContext = AssemblyLoadContext.GetLoadContext(currentAssembly);
        if (currentContext != null)
            currentContext.Unloading += OnPluginUnloadingRequested;
    }

    /// <summary>
    /// Use JSON array to create and execute the query as a Microsoft SQL Server batch operation.
    /// [Documentation](https://tasks.frends.com/tasks/frends-tasks/Frends.MicrosoftSQL.BatchOperation)
    /// </summary>
    /// <param name="input">Input parameters</param>
    /// <param name="connection">Properties to set up connection</param>
    /// <param name="options">Optional parameters</param>
    /// <param name="cancellationToken">Token generated by Frends to stop this Task.</param>
    /// <returns>object { bool Success, int RecordsAffected, object Error { string Message, Exception AdditionalInfo } }</returns>
    public static async Task<Result> BatchOperation(
        [PropertyTab] Input input,
        [PropertyTab] Connection connection,
        [PropertyTab] Options options,
        CancellationToken cancellationToken)
    {
        try
        {
            ValidationHandler.Run(connection);
            var connectionString = GetConnectionString(connection);
            if (connection.UseGivenUserCredentialsForRemoteConnections && !RuntimeInformation.IsOSPlatform(OSPlatform.Windows))
                throw new PlatformNotSupportedException("Simple impersonation feature is only supported on Windows machines.");
            if (!connection.UseGivenUserCredentialsForRemoteConnections)
                return await BatchOperationInternal(input, connectionString, options, cancellationToken).ConfigureAwait(false);

            var domainAndUsername = (connection.Username ?? string.Empty).Split('\\');
            if (domainAndUsername.Length != 2)
                throw new ArgumentException($@"Username field must be of format domain\username was: {connection.Username}");

            var credentials = new UserCredentials(domainAndUsername[0], domainAndUsername[1], connection.Password);
            using var handle = credentials.LogonUser(LogonType.NewCredentials);
            return await WindowsIdentity.RunImpersonatedAsync(
                    handle,
                    () => BatchOperationInternal(input, connectionString, options, cancellationToken))
                .ConfigureAwait(false);
        }
        catch (Exception ex)
        {
            return ex.Handle(options);
        }
    }

    private static async Task<Result> BatchOperationInternal(
        Input input,
        string connectionString,
        Options options,
        CancellationToken cancellationToken)
    {
        using var sqlConnection = new SqlConnection(connectionString);
        await sqlConnection.OpenAsync(cancellationToken).ConfigureAwait(false);
        if (options.SqlTransactionIsolationLevel is not SqlTransactionIsolationLevel.None)
        {
            using var transaction = sqlConnection.BeginTransaction(GetIsolationLevel(options));
            return await ExecuteHandler(input, options, sqlConnection, transaction, cancellationToken).ConfigureAwait(false);
        }
        else
        {
            return await ExecuteHandler(input, options, sqlConnection, null, cancellationToken).ConfigureAwait(false);
        }
    }

    private static async Task<Result> ExecuteHandler(Input input, Options options, SqlConnection connection, SqlTransaction transaction, CancellationToken cancellationToken)
    {
        var affectedRows = 0;
        try
        {
            var obj = JsonConvert.DeserializeObject<ExpandoObject[]>(input.InputJson, new ExpandoObjectConverter());

            affectedRows = await connection.ExecuteAsync(
                                input.Query,
                                param: obj,
                                commandTimeout: options.CommandTimeoutSeconds,
                                commandType: CommandType.Text,
                                transaction: transaction)
                            .ConfigureAwait(false);

            if (transaction != null)
                await transaction.CommitAsync(cancellationToken).ConfigureAwait(false);

            return new Result(true, affectedRows);
        }
        catch (Exception ex)
        {
            if (transaction is null)
                throw;

            try
            {
                await transaction.RollbackAsync(CancellationToken.None).ConfigureAwait(false);
            }
            catch (Exception rollbackEx)
            {
                throw new AggregateException("Execution failed and transaction rollback also failed.", ex, rollbackEx);
            }

            throw;
        }
    }

    private static string GetConnectionString(Connection connection)
    {
        if (!connection.UseGivenUserCredentialsForRemoteConnections)
            return connection.ConnectionString;

        var builder = new SqlConnectionStringBuilder(connection.ConnectionString);
        if (!builder.IntegratedSecurity)
        {
            throw new ArgumentException(
                "ConnectionString must use Integrated Security=true when UseGivenUserCredentialsForRemoteConnections is enabled.");
        }

        builder.Pooling = false;
        return builder.ConnectionString;
    }

    private static IsolationLevel GetIsolationLevel(Options options)
    {
        return options.SqlTransactionIsolationLevel switch
        {
            SqlTransactionIsolationLevel.Unspecified => IsolationLevel.Unspecified,
            SqlTransactionIsolationLevel.ReadUncommitted => IsolationLevel.ReadUncommitted,
            SqlTransactionIsolationLevel.ReadCommitted => IsolationLevel.ReadCommitted,
            SqlTransactionIsolationLevel.RepeatableRead => IsolationLevel.RepeatableRead,
            SqlTransactionIsolationLevel.Serializable => IsolationLevel.Serializable,
            SqlTransactionIsolationLevel.Snapshot => IsolationLevel.Snapshot,
            _ => IsolationLevel.ReadCommitted,
        };
    }

    private static void OnPluginUnloadingRequested(AssemblyLoadContext obj)
    {
        obj.Unloading -= OnPluginUnloadingRequested;
    }
}
